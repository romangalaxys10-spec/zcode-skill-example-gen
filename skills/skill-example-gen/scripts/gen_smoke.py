#!/usr/bin/env python3
"""gen_smoke.py: emit a smoke-test module for every script a plugin's skills reference.

Given a plugin directory (the plugin dir is a repo root: .zcode-plugin/,
skills/, commands/), this finds each script under
<plugin>/skills/<skill>/scripts/*.py and emits tests/test_scripts.py with,
per script:

  test_<slug>_help      run `python3 <script> --help`, assert exit 0 and
                        non-empty output
  test_<slug>_compile   py_compile the script byte by byte
  test_<slug>_happy     SKELETON: run the script with no args inside a
                        fresh temp dir; a crash (traceback) fails, a clean
                        or documented-usage exit passes. A FIXTURES hook
                        (a dict of argv + expected_rc) lets the agent
                        replace the default with the skill's own example.
  test_<slug>_fail      SKELETON: pass a bogus --no-such-flag probe; the
                        script must reject it (nonzero, no traceback).
                        Custom it when the probe is swallowed.

Safe by construction: fixtures live in tempfile.TemporaryDirectory, no
network, no pip, no pytest. The generated module has a plain runner:
`python3 tests/test_scripts.py` prints PASS/FAIL per test and exits 1 if
anything failed.

Exit codes:
  0  test module written (or --list printed the script inventory)
  1  no scripts found in the plugin (nothing to test)
  2  bad usage or unreadable plugin dir

Usage:
  python3 gen_smoke.py <plugin_dir> [--out PATH] [--list]

Python 3 stdlib only. Cross-OS.
"""
import argparse
import re
import sys
from pathlib import Path

TEMPLATE_HEAD = '''\
#!/usr/bin/env python3
"""Auto-generated smoke tests for the plugin's scripts.

Generated by skill-example-gen (gen_smoke.py). Customize the two
skeletons per script ({happy_skeletons} happy, {fail_skeletons} fail) to
match the documented examples in the skill's SKILL.md. The helper and
compile checks are finished as generated.

Run: python3 {out_rel}
"""
import py_compile
import subprocess
import sys
import tempfile
from pathlib import Path

PLUGIN_ROOT = Path(__file__).resolve().parent.parent
SCRIPTS = {
{script_entries}
}


def run_script(rel_path, argv, cwd=None, timeout=60):
    p = subprocess.run(
        [sys.executable, str(PLUGIN_ROOT / rel_path)] + argv,
        cwd=cwd or tempfile.gettempdir(),
        capture_output=True, text=True, timeout=timeout,
    )
    return p


def no_crash(p, label):
    """A traceback means the script broke, not that it failed gracefully."""
    assert "Traceback" not in p.stderr, label + " crashed: " + p.stderr[-400:]


{test_blocks}
def main():
    fns = sorted((n, f) for n, f in globals().items() if n.startswith("test_") and callable(f))
    failed = 0
    for name, fn in fns:
        try:
            fn()
            print("PASS " + name)
        except Exception as e:
            failed += 1
            print("FAIL " + name + ": " + str(e)[:200])
    print(("ALL PASSED (%d)" % len(fns)) if failed == 0 else ("FAILED %d of %d" % (failed, len(fns))))
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
'''

HAPPY_BLOCK = '''\
def test_{slug}_help():
    p = run_script({rel!r}, ["--help"])
    assert p.returncode == 0, "help exited " + str(p.returncode) + ": " + p.stderr[-200:]
    assert (p.stdout + p.stderr).strip(), "help printed nothing"


def test_{slug}_compile():
    py_compile.compile(str(PLUGIN_ROOT / {rel!r}), doraise=True)


def test_{slug}_happy():
    # SKELETON: default is a no-arg probe in a temp dir. Customize the
    # FIXTURES entry below with the skill's own example (argv, expected
    # exit code) to make this a real happy path.
    FIXTURES = {{}}  # {{}} -> default probe; e.g. {{"argv": ["--text", "hi"], "rc": 0}}
    with tempfile.TemporaryDirectory() as tmp:
        if FIXTURES:
            p = run_script({rel!r}, list(FIXTURES["argv"]), cwd=tmp)
            assert p.returncode == FIXTURES["rc"], "rc " + str(p.returncode)
        else:
            p = run_script({rel!r}, [], cwd=tmp)
            no_crash(p, "{slug} no-arg probe")
            assert p.returncode in (0, 1, 2), "unexpected rc " + str(p.returncode)
            print("INFO {slug}.happy: using default no-arg probe, rc " + str(p.returncode))


def test_{slug}_fail():
    # SKELETON: the bogus-flag probe must be rejected (argparse exit 2
    # or a usage error). If the script swallows unknown flags, replace
    # with the skill's documented failure input and its exit code.
    p = run_script({rel!r}, ["--no-such-flag"], cwd=tempfile.gettempdir())
    no_crash(p, "{slug} failure probe")
    assert p.returncode != 0, "failure probe was accepted (rc 0); customize this test"
'''


def slugify(name):
    return re.sub(r"[^a-z0-9]+", "_", Path(name).stem.lower()).strip("_") or "script"


def find_scripts(plugin_dir):
    out = []
    skills = plugin_dir / "skills"
    if not skills.is_dir():
        return out
    for skill_md in sorted(skills.glob("*/SKILL.md")):
        script_dir = skill_md.parent / "scripts"
        if script_dir.is_dir():
            for py in sorted(script_dir.glob("*.py")):
                out.append(py.relative_to(plugin_dir).as_posix())
    return out


def main(argv=None):
    parser = argparse.ArgumentParser(
        prog="gen_smoke.py",
        description="Emit tests/test_scripts.py with per-script smoke-test skeletons for a plugin.",
    )
    parser.add_argument("plugin_dir", help="plugin directory (repo root with skills/)")
    parser.add_argument("--out", help="output path (default <plugin_dir>/tests/test_scripts.py)")
    parser.add_argument("--list", action="store_true", help="print the script inventory and exit 0")
    args = parser.parse_args(argv)

    root = Path(args.plugin_dir)
    if not root.is_dir():
        print(f"error: not a directory: {root}", file=sys.stderr)
        return 2
    rels = find_scripts(root)
    if not rels:
        print(f"error: no scripts found under {root}/skills/*/scripts/", file=sys.stderr)
        return 1
    if args.list:
        for r in rels:
            print(r)
        return 0

    out = Path(args.out) if args.out else root / "tests" / "test_scripts.py"
    out.parent.mkdir(parents=True, exist_ok=True)
    script_entries = "\n".join(f'    {r!r},' for r in rels)
    blocks = []
    for r in rels:
        s = slugify(r)
        blocks.append(HAPPY_BLOCK.format(slug=s, rel=r))
    out_rel = out.name
    module = TEMPLATE_HEAD.format(
        happy_skeletons=len(rels), fail_skeletons=len(rels), out_rel=out_rel,
        script_entries=script_entries, test_blocks="\n\n".join(blocks),
    )
    out.write_text(module, encoding="utf-8")
    py_compile.compile(str(out), doraise=True)
    print(f"wrote {out} ({len(rels)} script(s), {4 * len(rels)} test(s)); byte-compiled OK")
    print("run it: python3 " + str(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
